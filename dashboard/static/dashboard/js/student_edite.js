function get_html(data, selectedId = null) {
  let s = "";

  for (let i = 0; i < data.length; i++) {
    if (data[i].id == selectedId) {
      s += `<option value="${data[i].id}" selected>${data[i].name}</option>`;
    } else {
      s += `<option value="${data[i].id}">${data[i].name}</option>`;
    }
  }

  return s;
}

